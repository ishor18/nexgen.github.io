  USING (bucket_id = 'nexgen-uploads' AND auth.uid() = owner);


-- ============================================================
-- 16. SYNC views_total FOR EXISTING AUTHORS
-- ============================================================
UPDATE public.profiles p
SET views_total = (
  SELECT COALESCE(SUM(b.views), 0)
  FROM public.blogs b
  WHERE b.author_id = p.id
);


