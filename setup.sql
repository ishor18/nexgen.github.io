-- 1. PROFILES TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id               UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  full_name        TEXT,
  email            TEXT UNIQUE,
  role             TEXT DEFAULT 'user' CHECK (role IN ('superadmin', 'admin', 'user')),
  balance          DECIMAL(12,2) DEFAULT 0.00,
  total_withdrawn  DECIMAL(12,2) DEFAULT 0.00,
  views_total      BIGINT DEFAULT 0,
  suspended_until  TIMESTAMP WITH TIME ZONE DEFAULT NULL,
  suspension_reason TEXT DEFAULT NULL,
  created_at       TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- Add any missing columns safely
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='balance')           THEN ALTER TABLE profiles ADD COLUMN balance          DECIMAL(12,2) DEFAULT 0.00; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='total_withdrawn')  THEN ALTER TABLE profiles ADD COLUMN total_withdrawn  DECIMAL(12,2) DEFAULT 0.00; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='views_total')      THEN ALTER TABLE profiles ADD COLUMN views_total      BIGINT DEFAULT 0; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='suspended_until')  THEN ALTER TABLE profiles ADD COLUMN suspended_until  TIMESTAMP WITH TIME ZONE DEFAULT NULL; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='suspension_reason') THEN ALTER TABLE profiles ADD COLUMN suspension_reason TEXT DEFAULT NULL; END IF;
END $$;

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;


